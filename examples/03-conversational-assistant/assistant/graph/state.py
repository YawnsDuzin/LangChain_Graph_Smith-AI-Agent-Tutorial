# assistant/graph/state.py
"""
============================================================================
LangGraph 상태(State) 정의 모듈
============================================================================

이 모듈은 AI 어시스턴트의 그래프 상태를 정의합니다.
LangGraph에서 상태는 그래프의 모든 노드가 공유하는 데이터 구조입니다.

핵심 개념:
    - State: 그래프 실행 중 노드 간에 전달되는 데이터
    - TypedDict: 타입이 지정된 딕셔너리로 상태 스키마 정의
    - Annotated: 상태 필드에 리듀서(reducer) 함수 연결

상태 설계 원칙:
    1. 명확한 타입 정의: 모든 필드에 타입 힌트 사용
    2. 불변성 고려: 상태는 가능한 불변으로 유지
    3. 리듀서 활용: 리스트 필드는 add_messages 같은 리듀서 사용

============================================================================
"""
from typing import TypedDict, Annotated, List, Optional, Any
from langgraph.graph.message import add_messages
from langchain_core.messages import BaseMessage


# ============================================================================
# 도구 호출 정보 타입 정의
# ============================================================================
class ToolCall(TypedDict):
    """
    ========================================================================
    도구 호출 정보를 담는 TypedDict
    ========================================================================

    TypedDict 상세 설명:
    --------------------------------------------------------------------------
    TypedDict는 Python의 typing 모듈에서 제공하는 타입으로,
    딕셔너리의 각 키에 대해 특정 타입을 지정할 수 있습니다.

    일반 dict와의 차이:
        - dict: {"key": value} 형태, 키와 값의 타입 제한 없음
        - TypedDict: 정해진 키만 사용, 각 키의 값 타입이 고정

    장점:
        - IDE에서 자동완성 지원
        - 타입 검사기(mypy)로 오류 조기 발견
        - 코드 가독성 향상

    사용 예시:
        # TypedDict 정의
        class Person(TypedDict):
            name: str
            age: int

        # 올바른 사용
        person: Person = {"name": "홍길동", "age": 30}

        # 타입 검사기가 오류 감지
        person["name"] = 123  # 에러: str 타입이어야 함
        person["height"] = 180  # 에러: 정의되지 않은 키

    Optional 사용:
        class Person(TypedDict):
            name: str
            nickname: Optional[str]  # None 허용

        person = {"name": "홍길동", "nickname": None}  # OK
    ========================================================================
    """
    # 호출할 도구의 이름
    # LangChain의 @tool 데코레이터로 정의된 함수명과 일치해야 함
    tool_name: str

    # 도구에 전달할 인자들 (딕셔너리 형태)
    # 예: {"query": "검색어", "max_results": 5}
    tool_args: dict

    # 이 도구 실행에 사용자 승인이 필요한지 여부
    # 위험한 도구(코드 실행 등)는 True로 설정
    requires_approval: bool

    # 사용자 승인 상태
    # None: 아직 확인 안함, True: 승인됨, False: 거부됨
    approved: Optional[bool]


# ============================================================================
# 어시스턴트 상태 정의
# ============================================================================
class AssistantState(TypedDict):
    """
    ========================================================================
    AI 어시스턴트의 그래프 상태
    ========================================================================

    LangGraph에서 상태(State)란?
    --------------------------------------------------------------------------
    상태는 그래프 실행 중 모든 노드가 읽고 쓸 수 있는 공유 데이터입니다.

    상태의 흐름:
        1. 초기 상태 생성 (create_initial_state 함수)
        2. 각 노드가 상태를 읽고 필요한 부분을 업데이트
        3. 다음 노드가 업데이트된 상태를 받아서 처리
        4. 최종 노드까지 상태가 전달되며 결과 누적

    상태 업데이트 방식:
        - 노드는 딕셔너리를 반환하여 상태를 업데이트
        - 반환된 키만 업데이트되고 나머지는 유지
        - 리듀서가 있는 필드는 리듀서 함수로 병합

    Annotated와 리듀서:
    --------------------------------------------------------------------------
    Annotated[타입, 리듀서]는 상태 필드에 리듀서 함수를 연결합니다.

    리듀서(Reducer)란?
        - 기존 값과 새 값을 받아 병합하는 함수
        - 함수 시그니처: (기존값, 새값) -> 병합된 값

    add_messages 리듀서:
        LangGraph에서 제공하는 메시지 리스트 병합 함수입니다.

        동작 방식:
            1. 새 메시지를 기존 리스트 끝에 추가
            2. 동일한 ID의 메시지가 있으면 덮어씀 (업데이트)

        사용 예시:
            messages: Annotated[list, add_messages]

            # 노드가 반환하면
            return {"messages": [new_message]}

            # 기존 리스트에 추가됨
            # [msg1, msg2] + [new_message] -> [msg1, msg2, new_message]

    리듀서가 없으면?
        - 새 값이 기존 값을 완전히 대체
        - 리스트의 경우 전체 리스트가 교체됨 (주의!)
    ========================================================================
    """

    # ========================================================================
    # 대화 메시지 리스트
    # ========================================================================
    # Annotated[list, add_messages] 상세 설명:
    #
    # Annotated는 타입에 메타데이터를 추가하는 Python 기능입니다.
    # 여기서는 list 타입에 add_messages 리듀서를 연결합니다.
    #
    # add_messages 리듀서의 동작:
    #   - 입력: (기존 메시지 리스트, 새 메시지 리스트)
    #   - 출력: 병합된 메시지 리스트
    #
    #   병합 규칙:
    #     1. 새 메시지에 id가 없으면 → 끝에 추가
    #     2. 새 메시지에 id가 있고 기존에 같은 id가 있으면 → 덮어씀
    #     3. 새 메시지에 id가 있고 기존에 없으면 → 끝에 추가
    #
    # 왜 리듀서가 필요한가?
    #   - 여러 노드가 메시지를 추가할 때 충돌 방지
    #   - 대화 기록의 일관성 유지
    #   - 병렬 실행 시 안전한 병합
    #
    # 사용 예시:
    #   # 노드에서 메시지 추가
    #   def my_node(state):
    #       new_msg = AIMessage(content="안녕하세요!")
    #       return {"messages": [new_msg]}  # 기존 리스트에 추가됨
    # ========================================================================
    messages: Annotated[list, add_messages]

    # ========================================================================
    # 현재 사용자 입력
    # ========================================================================
    # 사용자가 입력한 원본 텍스트를 저장합니다.
    # 이 값은 그래프 실행 중 변경되지 않습니다.
    user_input: str

    # ========================================================================
    # 의도 분석 결과
    # ========================================================================
    # 사용자 의도를 분류한 결과입니다.
    #
    # 가능한 값:
    #   - "chat": 일반 대화 (정보 요청, 잡담 등)
    #   - "tool_use": 도구 사용이 필요한 요청
    #   - "clarify": 추가 정보가 필요한 모호한 요청
    #
    # 의도에 따라 다른 처리 경로를 선택할 수 있습니다.
    intent: str  # chat, tool_use, clarify

    # ========================================================================
    # 도구 관련 상태
    # ========================================================================
    # 대기 중인 도구 호출 목록
    # LLM이 도구 사용을 결정했을 때 여기에 저장됩니다.
    pending_tool_calls: List[ToolCall]

    # 도구 실행 결과 목록
    # 각 도구 실행 후 결과가 여기에 추가됩니다.
    tool_results: List[dict]

    # ========================================================================
    # 워크플로우 제어 플래그
    # ========================================================================
    # 사용자 승인이 필요한지 여부
    # 위험한 도구(코드 실행 등) 사용 시 True로 설정
    requires_approval: bool

    # 사용자 승인 결과
    # None: 아직 응답 안함, True: 승인, False: 거부
    user_approved: Optional[bool]

    # ========================================================================
    # 응답 관련
    # ========================================================================
    # 최종 응답 텍스트
    response: str

    # 스트리밍 모드 여부
    # True면 응답을 토큰 단위로 스트리밍
    streaming: bool

    # ========================================================================
    # 세션 정보
    # ========================================================================
    # 대화 세션을 식별하는 고유 ID
    # 같은 session_id를 사용하면 대화가 이어집니다.
    session_id: str


# ============================================================================
# 초기 상태 생성 함수
# ============================================================================
def create_initial_state(
    user_input: str,
    session_id: str = "default"
) -> AssistantState:
    """
    ========================================================================
    초기 상태를 생성하는 팩토리 함수
    ========================================================================

    그래프 실행을 시작하려면 초기 상태가 필요합니다.
    이 함수는 사용자 입력을 받아 모든 필드가 초기화된 상태를 생성합니다.

    팩토리 함수 패턴:
    --------------------------------------------------------------------------
    팩토리 함수는 객체 생성을 캡슐화하는 디자인 패턴입니다.

    장점:
        - 생성 로직을 한 곳에서 관리
        - 기본값 설정을 일관되게 유지
        - 필요에 따라 다른 초기화 로직 추가 가능

    TypedDict 인스턴스 생성:
    --------------------------------------------------------------------------
    TypedDict는 클래스처럼 보이지만 실제로는 일반 딕셔너리입니다.
    AssistantState(...)는 타입 검사를 위한 것이고,
    런타임에는 일반 딕셔너리처럼 동작합니다.

    # 다음 두 코드는 런타임에 동일합니다:
    state = AssistantState(messages=[], user_input="안녕")
    state = {"messages": [], "user_input": "안녕"}

    하지만 TypedDict를 사용하면:
        - IDE 자동완성 지원
        - 타입 검사기로 오류 감지
        - 코드 가독성 향상

    Args:
        user_input: 사용자가 입력한 텍스트
        session_id: 대화 세션 ID (기본값: "default")

    Returns:
        AssistantState: 초기화된 상태 딕셔너리

    사용 예시:
        # 기본 사용
        state = create_initial_state("안녕하세요!")

        # 세션 ID 지정
        state = create_initial_state("안녕하세요!", session_id="user-123")

        # 그래프 실행
        result = graph.invoke(state)
    ========================================================================
    """
    return AssistantState(
        # 메시지 리스트는 빈 상태로 시작
        # process_input 노드에서 user_input을 HumanMessage로 변환하여 추가
        messages=[],

        # 원본 사용자 입력 저장
        user_input=user_input,

        # 의도는 아직 분석되지 않음 (빈 문자열)
        intent="",

        # 도구 관련 필드 초기화
        pending_tool_calls=[],
        tool_results=[],

        # 승인 관련 플래그 초기화
        requires_approval=False,
        user_approved=None,

        # 응답 초기화
        response="",

        # 기본적으로 스트리밍 활성화
        streaming=True,

        # 세션 ID 설정
        session_id=session_id
    )
