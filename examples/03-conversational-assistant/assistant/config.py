# assistant/config.py
"""
============================================================================
애플리케이션 설정 모듈
============================================================================

이 모듈은 AI 어시스턴트 애플리케이션의 전역 설정을 관리합니다.
환경 변수에서 API 키와 설정값을 로드하고, 유효성을 검증합니다.

주요 설정:
- API 키: OpenAI, Tavily (검색), LangSmith (모니터링)
- 모델 설정: 사용할 LLM 모델 및 파라미터
- LangSmith 프로젝트 설정

환경 변수 설정 방법:
    1. 프로젝트 루트에 .env 파일 생성
    2. 필요한 환경 변수 추가:
       OPENAI_API_KEY=sk-xxx...
       TAVILY_API_KEY=tvly-xxx...
       LANGCHAIN_API_KEY=ls__xxx...

============================================================================
"""
import os
from dotenv import load_dotenv

# ============================================================================
# dotenv로 환경 변수 로드
# ============================================================================
# load_dotenv() 함수 상세 설명:
#
# python-dotenv 라이브러리의 핵심 함수로, .env 파일에서 환경 변수를 로드합니다.
#
# 동작 원리:
#   1. 현재 디렉토리부터 상위 디렉토리로 .env 파일 검색
#   2. .env 파일의 KEY=VALUE 쌍을 파싱
#   3. os.environ에 환경 변수로 설정
#
# 주요 매개변수:
#   - dotenv_path (str, optional): .env 파일의 경로. 없으면 자동 검색
#   - override (bool): True면 기존 환경 변수를 덮어씀 (기본값: False)
#   - verbose (bool): True면 로드 과정을 출력 (기본값: False)
#
# .env 파일 형식:
#   # 주석
#   KEY=value
#   KEY="value with spaces"
#   MULTILINE="line1\nline2"
#
# 사용 예시:
#   # 기본 사용 (프로젝트 루트의 .env 파일 로드)
#   load_dotenv()
#
#   # 특정 파일 로드
#   load_dotenv(dotenv_path='/path/to/.env')
#
#   # 기존 환경 변수 덮어쓰기
#   load_dotenv(override=True)
#
# 보안 주의사항:
#   - .env 파일은 절대 git에 커밋하지 마세요
#   - .gitignore에 .env 추가 필수
#   - 프로덕션에서는 실제 환경 변수 사용 권장
# ============================================================================
load_dotenv()


class Config:
    """
    ========================================================================
    애플리케이션 설정 클래스
    ========================================================================

    모든 설정을 클래스 변수로 관리합니다.
    클래스 변수는 인스턴스 생성 없이 Config.SETTING_NAME으로 접근합니다.

    설계 패턴:
        - 클래스 변수 패턴: 전역 설정을 위한 단순하고 명확한 접근
        - 지연 로딩 없음: 애플리케이션 시작 시 모든 설정 즉시 로드

    사용 예시:
        from assistant.config import Config

        # 설정 검증
        Config.validate()

        # 설정 값 사용
        model = Config.LLM_MODEL
        api_key = Config.OPENAI_API_KEY
    ========================================================================
    """

    # ========================================================================
    # API Keys - 외부 서비스 인증용
    # ========================================================================

    # OpenAI API 키
    # ------------------------------------------------------------------------
    # os.getenv() 함수 상세 설명:
    #
    # 환경 변수의 값을 가져오는 Python 표준 라이브러리 함수입니다.
    #
    # 함수 시그니처:
    #   os.getenv(key, default=None)
    #
    # 매개변수:
    #   - key (str): 환경 변수 이름
    #   - default: 환경 변수가 없을 때 반환할 기본값 (기본: None)
    #
    # 반환값:
    #   - 환경 변수 값 (str) 또는 default
    #
    # 사용 예시:
    #   # 기본값 없음 (없으면 None)
    #   api_key = os.getenv("API_KEY")
    #
    #   # 기본값 지정
    #   port = os.getenv("PORT", "8080")
    #
    #   # 필수 환경 변수 (없으면 에러)
    #   api_key = os.getenv("API_KEY")
    #   if not api_key:
    #       raise ValueError("API_KEY is required")
    # ------------------------------------------------------------------------
    OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")

    # Tavily API 키 - 웹 검색 도구용
    # ------------------------------------------------------------------------
    # Tavily는 AI 애플리케이션에 최적화된 검색 API입니다.
    #
    # Tavily의 장점:
    #   - AI 친화적: 검색 결과가 LLM이 처리하기 좋은 형태로 제공
    #   - 실시간 검색: 최신 정보 접근 가능
    #   - 요약 기능: 검색 결과를 자동으로 요약
    #
    # API 키 발급: https://tavily.com
    # ------------------------------------------------------------------------
    TAVILY_API_KEY = os.getenv("TAVILY_API_KEY")

    # LangSmith API 키 - 모니터링 및 추적용
    # ------------------------------------------------------------------------
    # LangSmith는 LangChain 애플리케이션의 관찰성(Observability) 플랫폼입니다.
    #
    # LangSmith의 기능:
    #   - 트레이싱: 모든 LLM 호출과 체인 실행 기록
    #   - 디버깅: 에러 발생 시 상세한 컨텍스트 제공
    #   - 평가: 프롬프트와 응답의 품질 분석
    #   - 데이터셋: 테스트용 데이터셋 관리
    #
    # API 키 발급: https://smith.langchain.com
    # ------------------------------------------------------------------------
    LANGCHAIN_API_KEY = os.getenv("LANGCHAIN_API_KEY")

    # ========================================================================
    # Model Settings - LLM 모델 설정
    # ========================================================================

    # 사용할 OpenAI 모델
    # ------------------------------------------------------------------------
    # GPT-4 모델 옵션:
    #   - "gpt-4": 가장 강력한 모델, 복잡한 추론에 적합
    #   - "gpt-4-turbo": GPT-4의 빠른 버전, 비용 효율적
    #   - "gpt-4o": 최신 GPT-4 Omni 모델, 멀티모달 지원
    #   - "gpt-4o-mini": 경량화된 GPT-4o, 비용 최적화
    #
    # GPT-3.5 모델 옵션:
    #   - "gpt-3.5-turbo": 빠르고 저렴, 간단한 작업에 적합
    #
    # 선택 기준:
    #   - 복잡한 추론/코드 생성: gpt-4 또는 gpt-4-turbo
    #   - 일반 대화/간단한 작업: gpt-3.5-turbo
    #   - 비용과 성능의 균형: gpt-4o-mini
    # ------------------------------------------------------------------------
    LLM_MODEL = "gpt-4"

    # Temperature 설정
    # ------------------------------------------------------------------------
    # Temperature는 LLM 응답의 창의성/무작위성을 제어합니다.
    #
    # 값의 범위: 0.0 ~ 2.0
    #
    # 값의 의미:
    #   - 0.0: 가장 결정론적. 항상 가장 가능성 높은 토큰 선택
    #          코드 생성, 수학 문제, 팩트 기반 질문에 적합
    #
    #   - 0.3~0.5: 낮은 창의성. 일관된 응답이 필요할 때
    #              고객 서비스, 기술 문서 작성에 적합
    #
    #   - 0.7: 균형점. 창의성과 일관성의 적절한 조합
    #          일반적인 대화형 AI에 권장되는 값
    #
    #   - 1.0: 높은 창의성. 다양한 응답 생성
    #          브레인스토밍, 창작 활동에 적합
    #
    #   - 1.5~2.0: 매우 높은 무작위성. 예측하기 어려운 응답
    #              실험적 용도로만 사용
    #
    # 내부 동작:
    #   Temperature는 softmax 함수의 출력을 조절합니다.
    #   낮은 값은 확률 분포를 날카롭게, 높은 값은 평평하게 만듭니다.
    # ------------------------------------------------------------------------
    TEMPERATURE = 0.7

    # ========================================================================
    # LangSmith 설정
    # ========================================================================

    # LangSmith 프로젝트 이름
    # ------------------------------------------------------------------------
    # 프로젝트는 LangSmith에서 트레이스를 그룹화하는 단위입니다.
    #
    # 프로젝트 관리 방법:
    #   - 환경별 분리: dev-project, staging-project, prod-project
    #   - 기능별 분리: rag-chatbot, multi-agent, assistant
    #   - 버전별 분리: project-v1, project-v2
    #
    # 환경 변수 우선순위:
    #   1. LANGCHAIN_PROJECT 환경 변수가 설정되어 있으면 사용
    #   2. 없으면 기본값 "ai-assistant-tutorial" 사용
    #
    # LangSmith 대시보드에서 프로젝트별로 트레이스를 필터링할 수 있습니다.
    # ------------------------------------------------------------------------
    LANGCHAIN_PROJECT = os.getenv("LANGCHAIN_PROJECT", "ai-assistant-tutorial")

    @classmethod
    def validate(cls):
        """
        ====================================================================
        설정 검증 메서드
        ====================================================================

        필수 설정값이 올바르게 설정되었는지 확인합니다.
        애플리케이션 시작 시 반드시 호출해야 합니다.

        @classmethod 데코레이터:
            클래스 메서드를 정의합니다. 인스턴스 없이 호출할 수 있습니다.
            첫 번째 매개변수로 클래스(cls)를 받습니다.

        사용법:
            # 애플리케이션 시작 시
            Config.validate()  # 검증 실패 시 ValueError 발생

        검증 항목:
            - OPENAI_API_KEY: 필수 (LLM 사용에 필요)
            - TAVILY_API_KEY: 선택 (웹 검색 기능에 필요)
            - LANGCHAIN_API_KEY: 선택 (LangSmith 모니터링에 필요)

        Raises:
            ValueError: 필수 설정이 없을 때 발생
        ====================================================================
        """
        # OpenAI API 키는 필수
        if not cls.OPENAI_API_KEY:
            raise ValueError("OPENAI_API_KEY가 설정되지 않았습니다.")

        # 검증 성공 메시지 출력
        # 이모지는 터미널에서 시각적 피드백을 제공합니다
        print("✅ 설정 검증 완료")
